# Script para calcular promedio 3 numeros // Diego Alejandro Salcido Pérez...


num1 = float(input("Ingrese el primer numero: "))
num2 = float(input("Ingrese el segundo numero: "))
num3 = float(input("Ingrese el tercer numero: "))


promedio = (
    num1 + num2 + num3) / 3


print("__El promedio es__"
      , promedio)
